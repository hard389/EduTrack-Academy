import PDFDocument from "pdfkit";

type ReportRecord = Record<string, unknown>;

function clean(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

function isRecord(value: unknown): value is ReportRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function buildRemarks(reportData: ReportRecord): string {
  const remarks = clean(reportData.remarks);

  if (remarks) return remarks.slice(0, 3000);

  if (Array.isArray(reportData.remarkItems)) {
    const items = reportData.remarkItems
      .filter(isRecord)
      .map((item) =>
        `${clean(item.category)}: ${clean(item.remarkText)}`.trim(),
      )
      .filter(Boolean)
      .join("\n");

    return items.slice(0, 3000) || "No saved remarks";
  }

  return "No saved remarks";
}

export async function buildMonthlyReportPdf(
  reportData: ReportRecord,
  student: ReportRecord,
  className: string,
  teacherName: string,
  academyName: string,
  monthLabel: string,
): Promise<Buffer> {
  const pdf = new PDFDocument({
    size: "A4",
    margins: { top: 48, bottom: 48, left: 48, right: 48 },
    compress: true,
  });

  const chunks: Buffer[] = [];

  const completed = new Promise<Buffer>((resolve, reject) => {
    pdf.on("data", (chunk: Buffer | string) => {
      chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
    });

    pdf.on("end", () => resolve(Buffer.concat(chunks)));
    pdf.on("error", reject);
  });

  pdf
    .fillColor("#172033")
    .fontSize(20)
    .font("Helvetica-Bold")
    .text("Monthly Student Report", { align: "center" });

  pdf
    .moveDown(0.3)
    .fillColor("#526078")
    .fontSize(10)
    .font("Helvetica")
    .text(academyName, { align: "center" });

  pdf.moveDown(0.2).text(`Teacher: ${teacherName}`);
  pdf.moveDown(0.8).strokeColor("#d7deea")
    .moveTo(48, pdf.y).lineTo(547, pdf.y).stroke();
  pdf.moveDown(0.8);

  const fields: Array<[string, string]> = [
    ["Month", monthLabel],
    ["Class", className],
    ["Student", clean(student.name) || clean(reportData.studentName) || "Student"],
    ["Father/Guardian", clean(student.fatherName) || clean(reportData.fatherName) || "Not provided"],
    ["Roll Number", clean(student.rollNo) || clean(reportData.rollNo) || "—"],
    ["Category", clean(reportData.category) || "—"],
    ["Homework Grade", clean(reportData.homeworkGrade) || "—"],
    ["Behavior Grade", clean(reportData.behaviorGrade) || "—"],
    ["Participation Grade", clean(reportData.participationGrade) || "—"],
    ["Performance Grade", clean(reportData.performanceGrade) || "—"],
    ["Attendance", clean(reportData.attendanceRate) || "—"],
    ["Quiz Score", clean(reportData.quizScore) || "—"],
    ["Fee Status", clean(reportData.feeStatus) || "Unrecorded"],
  ];

  for (const [label, value] of fields) {
    pdf.font("Helvetica-Bold").fontSize(10)
      .fillColor("#172033").text(`${label}: `, { continued: true });

    pdf.font("Helvetica").fillColor("#303b50")
      .text(value, { lineGap: 2 });

    pdf.moveDown(0.25);
  }

  pdf.moveDown(0.4)
    .font("Helvetica-Bold")
    .fontSize(11)
    .fillColor("#172033")
    .text("Remarks");

  pdf.moveDown(0.2)
    .font("Helvetica")
    .fontSize(10)
    .fillColor("#303b50")
    .text(buildRemarks(reportData), { lineGap: 3 });

  pdf.moveDown(1)
    .fontSize(8)
    .fillColor("#667085")
    .text(
      "Generated by EduTrack for the student's parent/guardian.",
      { align: "center" },
    );

  pdf.end();

  return completed;
}
